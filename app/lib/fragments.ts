/**
 * Product card fragment used by every product grid/rail.
 * Review metafields (`reviews.rating`, `reviews.rating_count`) are the
 * standard Shopify review metafields written by most review apps; when absent
 * no rating is shown.
 */
export const PRODUCT_CARD_FRAGMENT = `#graphql
  fragment MoneyProductCard on MoneyV2 {
    amount
    currencyCode
  }
  fragment ProductCard on Product {
    id
    handle
    title
    vendor
    publishedAt
    availableForSale
    tags
    featuredImage {
      id
      altText
      url
      width
      height
    }
    images(first: 2) {
      nodes {
        id
        altText
        url
        width
        height
      }
    }
    priceRange {
      minVariantPrice {
        ...MoneyProductCard
      }
      maxVariantPrice {
        ...MoneyProductCard
      }
    }
    compareAtPriceRange {
      minVariantPrice {
        ...MoneyProductCard
      }
    }
    variantsCount {
      count
    }
    selectedOrFirstAvailableVariant(
      selectedOptions: []
      ignoreUnknownOptions: true
      caseInsensitiveMatch: true
    ) {
      id
      title
      availableForSale
      price {
        ...MoneyProductCard
      }
      compareAtPrice {
        ...MoneyProductCard
      }
      image {
        id
        url
        altText
        width
        height
      }
      selectedOptions {
        name
        value
      }
      product {
        handle
        title
      }
    }
    rating: metafield(namespace: "reviews", key: "rating") {
      value
    }
    ratingCount: metafield(namespace: "reviews", key: "rating_count") {
      value
    }
  }
` as const;

